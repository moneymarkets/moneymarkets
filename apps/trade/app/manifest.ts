import type { MetadataRoute } from 'next';

import { BASE_PATH } from '../lib/basePath';

/** PWA manifest (spec §6.5). `standalone` is what the install banner promises. */
export default function manifest(): MetadataRoute.Manifest {
  return {
    name: 'MoneyMarkets',
    short_name: 'MoneyMarkets',
    description: 'Your dollars. Trading on Monad. No gas, no seed phrase.',
    start_url: `${BASE_PATH}/home`,
    scope: `${BASE_PATH}/`,
    display: 'standalone',
    // Redesign (2026-09-30): the app's background is now the dark-green surface
    // at every theme's splash screen, matching the new default theme-color below —
    // display stays 'standalone', untouched (REDESIGN-PROMPT.txt PWA shell §).
    background_color: '#0B1A14',
    theme_color: '#0B1A14',
    orientation: 'portrait',
    // Generated by `node scripts/icons.mjs` from the design tokens; `maskable` is a
    // separate file because Android crops to a circle and a full-bleed mark loses
    // its corners, while iOS applies its own mask and wants the full bleed.
    icons: [
      { src: `${BASE_PATH}/icon-192.png`, sizes: '192x192', type: 'image/png', purpose: 'any' },
      { src: `${BASE_PATH}/icon-512.png`, sizes: '512x512', type: 'image/png', purpose: 'any' },
      {
        src: `${BASE_PATH}/icon-maskable-512.png`,
        sizes: '512x512',
        type: 'image/png',
        purpose: 'maskable',
      },
    ],
  };
}
